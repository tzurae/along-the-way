#!/usr/bin/env python3
"""Generate the browser airport search data from the pinned airportsdata CSV."""

from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
import pathlib
import urllib.request

SOURCE_COMMIT = "47ae282a8491758e6dafe28d4139539e561b54d5"
SOURCE_URL = (
    "https://raw.githubusercontent.com/mborsetti/airportsdata/"
    f"{SOURCE_COMMIT}/airportsdata/airports.csv"
)
SOURCE_SHA256 = "516c57d9d999f7a3be28ca649d2badbe3b972f07e57dc6173ab973b72d51cf52"
DEFAULT_OUTPUT = pathlib.Path(__file__).resolve().parents[1] / "apps/web/src/airport-data.generated.ts"


def source_bytes(source: str | None) -> bytes:
    if source:
        return pathlib.Path(source).read_bytes()
    with urllib.request.urlopen(SOURCE_URL) as response:
        return response.read()


def airport_rows(raw: bytes) -> list[list[object]]:
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SOURCE_SHA256:
        raise SystemExit(f"Pinned airport CSV hash mismatch: expected {SOURCE_SHA256}, received {digest}")

    selected: dict[str, tuple[str, str, str, str, float, float, str]] = {}
    reader = csv.DictReader(io.StringIO(raw.decode("utf-8")))
    for row in reader:
        code = row["iata"].strip().upper()
        if len(code) != 3 or not code.isascii() or not code.isalpha():
            continue
        candidate = (
            row["icao"].strip(),
            row["name"].strip(),
            row["city"].strip(),
            row["country"].strip().upper(),
            float(row["lat"]),
            float(row["lon"]),
            row["tz"].strip(),
        )
        current = selected.get(code)
        if current is None or candidate < current:
            selected[code] = candidate

    return [
        [code, name, city, country, latitude, longitude, time_zone]
        for code, (_icao, name, city, country, latitude, longitude, time_zone)
        in sorted(selected.items())
    ]


def render(rows: list[list[object]]) -> str:
    source = f"https://github.com/mborsetti/airportsdata/tree/{SOURCE_COMMIT}"
    payload = json.dumps(rows, ensure_ascii=False, separators=(",", ":"))
    return f'''/*
 * GENERATED by scripts/generate-airports.py. Do not edit by hand.
 * Source: airportsdata v20260905, {source}
 * Commit: {SOURCE_COMMIT}
 * License: MIT, Copyright (c) 2020- Mike Borsetti and (c) 2014 mwgg.
 * Time zones were originally sourced by airportsdata from TimeZoneDB.
 * Retained fields: IATA code, English name, city, ISO country code, latitude,
 * longitude, and IANA time zone. Blank IATA rows are omitted; duplicate IATA
 * codes resolve deterministically to the lexicographically first source row.
 */
import type {{ AirportRecord }} from "./airport-data";

export const AIRPORT_DATA_COMMIT = "{SOURCE_COMMIT}";

const airports: readonly AirportRecord[] = {payload};
export default airports;
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", help="local copy of the pinned airports.csv")
    parser.add_argument("--output", type=pathlib.Path, default=DEFAULT_OUTPUT)
    arguments = parser.parse_args()
    rows = airport_rows(source_bytes(arguments.source))
    arguments.output.write_text(render(rows), encoding="utf-8")
    print(f"wrote {len(rows)} IATA airports to {arguments.output}")


if __name__ == "__main__":
    main()
